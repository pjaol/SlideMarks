"""Word specimen: the same checks as the PowerPoint deck, in Word tables and
paragraphs, with the font embedded so no install is needed."""

from pathlib import Path

from docx import Document
from docx.enum.section import WD_ORIENT
from docx.enum.table import WD_CELL_VERTICAL_ALIGNMENT, WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.opc.constants import RELATIONSHIP_TYPE as RT
from docx.opc.packuri import PackURI
from docx.opc.part import Part
from docx.oxml import parse_xml
from docx.oxml.ns import nsdecls, qn
from docx.shared import Inches, Pt, RGBColor
from lxml import etree

from .font import FAMILY
from .office_fonts import font_key_for, obfuscate_odttf
from .specimen_content import LADDER_PT, SCORECARD_HEADER, SCORECARD_ROWS, alias_rows, families, preferred_char, visible_text

TEXT_FONT = "Calibri"
DARK = "14161A"
LIGHT = RGBColor(0xF3, 0xF4, 0xF6)
MUTED = RGBColor(0x6B, 0x72, 0x80)


def _set_font(run, typeface: str):
    """Assign every script slot; Word may treat PUA characters as East Asian."""
    rpr = run._r.get_or_add_rPr()
    fonts = rpr.find(qn("w:rFonts"))
    if fonts is None:
        fonts = rpr.makeelement(qn("w:rFonts"), {})
        rpr.insert(0, fonts)
    for attr in ("w:ascii", "w:hAnsi", "w:eastAsia", "w:cs"):
        fonts.set(qn(attr), typeface)


def _add_run(paragraph, text, typeface, size_pt, color=None, bold=False):
    run = paragraph.add_run(text)
    run.font.size = Pt(size_pt)
    run.font.bold = bold
    if color is not None:
        run.font.color.rgb = color
    _set_font(run, typeface)
    return run


def _shade(cell, hex_fill):
    cell._tc.get_or_add_tcPr().append(parse_xml(f'<w:shd {nsdecls("w")} w:val="clear" w:color="auto" w:fill="{hex_fill}"/>'))


def _cell(cell, text, typeface, size_pt, align=WD_ALIGN_PARAGRAPH.CENTER, color=None, fill=None, bold=False):
    p = cell.paragraphs[0]
    p.alignment = align
    p.paragraph_format.space_before = Pt(3)
    p.paragraph_format.space_after = Pt(3)
    _add_run(p, text, typeface, size_pt, color, bold)
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    if fill is not None:
        _shade(cell, fill)


def _heading(doc, text, sub=None):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(18)
    _add_run(p, text, TEXT_FONT, 16, bold=True)
    if sub:
        _add_run(doc.add_paragraph(), sub, TEXT_FONT, 10, color=MUTED)


def render(manifest, ttf_path: Path, out_path: Path):
    doc = Document()
    section = doc.sections[0]
    section.orientation = WD_ORIENT.LANDSCAPE
    section.page_width, section.page_height = section.page_height, section.page_width
    for side in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
        setattr(section, side, Inches(0.7))

    symbols = manifest["symbols"]
    ch = {s["id"]: chr(int(s["codepoint"], 16)) for s in symbols}
    fams = families(manifest)

    p = doc.add_paragraph()
    _add_run(p, "SlideMarks Word specimen", TEXT_FONT, 22, bold=True)
    _add_run(doc.add_paragraph(),
             "SlideMarks is embedded in this file; no install needed. Empty boxes mean the embedded font was not loaded. "
             "Select a cell and change font colour and size: glyphs must behave exactly like text. "
             "Regenerated by `slidemarks build`; edit the generator, not this document.",
             TEXT_FONT, 10, color=MUTED)

    # 1 · Families
    for size in (14, 20):
        _heading(doc, f"Families · {size}pt", "Each family in one row of centred table cells. Compare outer size, centre and weight.")
        width = max(len(m) for _, _, m in fams)
        t = doc.add_table(rows=len(fams), cols=width + 1, style="Table Grid")
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        for r, (_, title, members) in enumerate(fams):
            _cell(t.cell(r, 0), title, TEXT_FONT, 9, align=WD_ALIGN_PARAGRAPH.LEFT)
            for c in range(width):
                _cell(t.cell(r, c + 1), ch[members[c]["id"]] if c < len(members) else "", FAMILY, size)

    # 2 · Scorecard in light and dark
    for size, dark in ((12, False), (18, False), (18, True)):
        _heading(doc, f"Scorecard · {size}pt{' · dark' if dark else ''}",
                 "Typical usage: no per-cell adjustment.")
        t = doc.add_table(rows=len(SCORECARD_ROWS) + 1, cols=len(SCORECARD_HEADER), style="Table Grid")
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        fg, bg = (LIGHT, DARK) if dark else (None, None)
        for c, h in enumerate(SCORECARD_HEADER):
            _cell(t.cell(0, c), h, TEXT_FONT, 11, align=WD_ALIGN_PARAGRAPH.LEFT if c == 0 else WD_ALIGN_PARAGRAPH.CENTER,
                  bold=True, color=fg, fill=bg)
        for r, (label, *ids) in enumerate(SCORECARD_ROWS, start=1):
            _cell(t.cell(r, 0), label, TEXT_FONT, 11, align=WD_ALIGN_PARAGRAPH.LEFT, color=fg, fill=bg)
            for c, gid in enumerate(ids, start=1):
                _cell(t.cell(r, c), ch[gid], FAMILY, size, color=fg, fill=bg)

    by_id = {s["id"]: s for s in symbols}

    # Accessibility · symbol plus visible text
    _heading(doc, "Accessible scorecard · 12pt",
             "Each symbol is paired with visible text in the same cell. Screen readers read the text; the glyph adds the visual.")
    t = doc.add_table(rows=len(SCORECARD_ROWS) + 1, cols=len(SCORECARD_HEADER), style="Table Grid")
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for c, h in enumerate(SCORECARD_HEADER):
        _cell(t.cell(0, c), h, TEXT_FONT, 11, align=WD_ALIGN_PARAGRAPH.LEFT if c == 0 else WD_ALIGN_PARAGRAPH.CENTER, bold=True)
    for r, (label, *ids) in enumerate(SCORECARD_ROWS, start=1):
        _cell(t.cell(r, 0), label, TEXT_FONT, 11, align=WD_ALIGN_PARAGRAPH.LEFT)
        for c, gid in enumerate(ids, start=1):
            cell = t.cell(r, c)
            _cell(cell, preferred_char(by_id[gid]), FAMILY, 12)
            _add_run(cell.paragraphs[0], f" {visible_text(by_id[gid])}", TEXT_FONT, 10)

    # Accessibility · encoding test
    _heading(doc, "Encoding test",
             "Both glyph columns use SlideMarks and must look identical. Read each row with a screen reader and record what it says.")
    pairs = alias_rows(manifest)
    t = doc.add_table(rows=len(pairs) + 1, cols=4, style="Table Grid")
    for c, h in enumerate(("Glyph", "PUA", "Standard", "Unicode name of the standard character")):
        _cell(t.cell(0, c), h, TEXT_FONT, 11, align=WD_ALIGN_PARAGRAPH.LEFT if c in (0, 3) else WD_ALIGN_PARAGRAPH.CENTER, bold=True)
    for r, (sym, pua, alias, uname) in enumerate(pairs, start=1):
        _cell(t.cell(r, 0), sym["name"], TEXT_FONT, 11, align=WD_ALIGN_PARAGRAPH.LEFT)
        _cell(t.cell(r, 1), pua, FAMILY, 18)
        _cell(t.cell(r, 2), alias, FAMILY, 18)
        _cell(t.cell(r, 3), f"U+{ord(alias):04X} {uname}", TEXT_FONT, 11, align=WD_ALIGN_PARAGRAPH.LEFT)

    # 3 · Size ladder: glyphs inline with body text
    _heading(doc, "Size ladder", "Glyphs mixed with Calibri text in one paragraph. Check baseline and cap alignment at each size.")
    for pt in LADDER_PT:
        _add_run(doc.add_paragraph(), f"{pt}pt", TEXT_FONT, 10, bold=True, color=MUTED)
        for _, title, members in fams:
            p = doc.add_paragraph()
            p.paragraph_format.space_after = Pt(2)
            _add_run(p, "Hx 50% ", TEXT_FONT, pt)
            _add_run(p, " ".join(ch[s["id"]] for s in members), FAMILY, pt)
            _add_run(p, f" {title}", TEXT_FONT, pt)

    _embed_font(doc, ttf_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(out_path))


def _embed_font(doc, ttf_path: Path):
    """Embed the full font as an obfuscated .odttf referenced from fontTable.xml."""
    package = doc.part.package
    font_table = next(p for p in package.iter_parts() if p.partname == "/word/fontTable.xml")
    key = font_key_for(FAMILY)
    font_part = Part(PackURI("/word/fonts/font1.odttf"),
                     "application/vnd.openxmlformats-officedocument.obfuscatedFont",
                     obfuscate_odttf(ttf_path, key), package)
    rid = font_table.relate_to(font_part, RT.FONT)

    fonts = parse_xml(font_table.blob)
    fonts.append(parse_xml(
        f'<w:font {nsdecls("w", "r")} w:name="{FAMILY}">'
        '<w:charset w:val="00"/><w:family w:val="auto"/><w:pitch w:val="variable"/>'
        f'<w:embedRegular r:id="{rid}" w:fontKey="{{{str(key).upper()}}}"/>'
        "</w:font>"
    ))
    font_table._blob = etree.tostring(fonts, xml_declaration=True, encoding="UTF-8", standalone=True)

    # Schema order: embedTrueTypeFonts comes after w:zoom and before w:proofState.
    settings = doc.settings.element
    embed = settings.makeelement(qn("w:embedTrueTypeFonts"), {})
    zoom = settings.find(qn("w:zoom"))
    if zoom is not None:
        zoom.addnext(embed)
    else:
        settings.insert(0, embed)
